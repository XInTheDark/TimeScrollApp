#!/usr/bin/env python3
"""Regenerates TimeScrollDev/PrivateBrowsing/PrivateBrowsingMarkers+Generated.swift.

Reads the private-window title strings from the browsers' own translations, so a browser update
or a new language is a re-run rather than hand editing. See docs/private-browsing-detection.md.

Usage:
  git clone --depth 1 https://github.com/mozilla-l10n/firefox-l10n.git /path/to/firefox-l10n
  scripts/generate_private_browsing_markers.py --firefox-l10n /path/to/firefox-l10n
"""
import argparse
import glob
import os
import re
import struct
import sys

OUTPUT = os.path.join(os.path.dirname(__file__), "..", "TimeScrollDev", "PrivateBrowsing",
                      "PrivateBrowsingMarkers+Generated.swift")
BIDI_MARKS = re.compile("[‎‏‪-‮⁦-⁩]")


def read_pak(path):
    """Parses a Chromium version 5 .pak file into {resource id: bytes}."""
    with open(path, "rb") as f:
        data = f.read()
    version = struct.unpack("<I", data[:4])[0]
    if version != 5:
        sys.exit(f"Unsupported pak version {version}: {path}")
    count, alias_count = struct.unpack("<HH", data[8:12])
    entries = [struct.unpack("<HI", data[12 + 6 * i:18 + 6 * i]) for i in range(count + 1)]
    resources = {entries[i][0]: data[entries[i][1]:entries[i + 1][1]] for i in range(count)}
    aliases_at = 12 + 6 * (count + 1)
    for i in range(alias_count):
        alias, index = struct.unpack("<HH", data[aliases_at + 4 * i:aliases_at + 4 * i + 4])
        resources[alias] = resources[entries[index][0]]
    return resources


def chromium_formats(app, framework, english):
    """All translations of the private title format, found by its English text."""
    root = f"/Applications/{app}.app/Contents/Frameworks/{framework}.framework/Versions/Current/Resources"
    english_pak = read_pak(f"{root}/en.lproj/locale.pak")
    ids = [key for key, value in english_pak.items() if value == english.encode()]
    if not ids:
        sys.exit(f"{english!r} not found in {app}; its resource may have changed")
    formats = set()
    for path in glob.glob(f"{root}/*.lproj/locale.pak"):
        value = read_pak(path).get(ids[-1], b"").decode("utf-8", "replace")
        value = BIDI_MARKS.sub("", value)
        if "$1" in value:
            formats.add(value)
    return formats


def firefox_suffixes(l10n_root):
    """The Private Browsing title suffix of each Firefox language, as shown on macOS."""
    suffixes = {"Private Browsing"}
    pattern = re.compile(r"^browser-main-private-suffix-for-content\s*=\s*(.+)$", re.M)
    for path in glob.glob(os.path.join(l10n_root, "*", "browser", "browser", "browser.ftl")):
        with open(path, encoding="utf-8") as f:
            match = pattern.search(f.read())
        if match and "{" not in match.group(1):
            suffixes.add(BIDI_MARKS.sub("", match.group(1)).strip())
    return suffixes


def swift_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def affix_list(formats):
    lines = []
    for value in sorted(formats):
        prefix, suffix = value.split("$1", 1)
        lines.append(f"    TitleAffix(prefix: {swift_string(prefix)}, suffix: {swift_string(suffix)}),")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--firefox-l10n", required=True)
    args = parser.parse_args()

    chrome = chromium_formats("Google Chrome", "Google Chrome Framework", "$1 (Incognito)")
    brave = chromium_formats("Brave Browser", "Brave Browser Framework", "$1 (Private)")
    firefox = {f"$1 — {suffix}" for suffix in firefox_suffixes(args.firefox_l10n)}

    source = f"""// Generated by scripts/generate_private_browsing_markers.py. Do not edit by hand.

extension PrivateBrowsingMarkers {{
  static let chromeTitleAffixes: [TitleAffix] = [
{affix_list(chrome)}
  ]

  static let braveTitleAffixes: [TitleAffix] = [
{affix_list(brave)}
  ]

  static let firefoxTitleAffixes: [TitleAffix] = [
{affix_list(firefox)}
  ]
}}
"""
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(source)
    print(f"chrome={len(chrome)} brave={len(brave)} firefox={len(firefox)}")


if __name__ == "__main__":
    main()
